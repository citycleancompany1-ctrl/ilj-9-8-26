const STORAGE_KEY = 'INDIANLALAJI_SAAS_STATE_V1';

export function loadPlatformState(): PlatformState {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      // Validate structure
      if (parsed.shops && parsed.pricingPackages) {
        // Enforce exactly 1 master pricing plan
        if (Array.isArray(parsed.pricingPackages) && parsed.pricingPackages.length > 1) {
          parsed.pricingPackages = [parsed.pricingPackages[0]];
        }
        if (!parsed.themes || !Array.isArray(parsed.themes) || parsed.themes.length === 0) {
          parsed.themes = INDIAN_LAYOUT_THEMES;
        }
        if (!parsed.saasBackups) {
          parsed.saasBackups = [];
        }
        return parsed;
      }
    }
  } catch (e) {
    console.error('Failed to load local state:', e);
  }
  return INITIAL_STATE;
}

export function savePlatformState(state: PlatformState): void {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(state));
  } catch (e) {
    console.error('Failed to save local state:', e);
  }
}
